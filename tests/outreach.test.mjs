import {strict as assert} from 'node:assert';
import {switchDraft,editDraft,mergeChanges} from '../.test-build/outreach.js';
const base={id:'lead',company:'Example',notes:'Keep notes',research:{channel:'Email',sourceUrl:'https://example.com/evidence'},draft:'Hi Sam,\n\nA specific observation. Here is a focused project.\n\nBest,\nLinda',draftEdited:true,custom:'keep'};
let lead={...base,...switchDraft(base,'Connection note')};
assert.ok(lead.draft.length<=300);
lead={...lead,...editDraft(lead,'Hi Sam, a personal connection note.')};
lead={...lead,...switchDraft(lead,'Email')};
assert.equal(lead.draft,base.draft);
lead={...lead,...editDraft(lead,'Edited email','Specific subject')};
lead={...lead,...switchDraft(lead,'Connection note')};
assert.equal(lead.draft,'Hi Sam, a personal connection note.');
lead={...lead,...switchDraft(lead,'Email')};
assert.equal(lead.draft,'Edited email');
assert.equal(lead.drafts.Email.subject,'Specific subject');
assert.equal(lead.notes,base.notes);assert.equal(lead.custom,'keep');
const latest={...base,research:{...base.research,linkedIn:'https://linkedin.com/in/verified'},notes:'Concurrent notes',newField:'preserved'};
const merged=mergeChanges(latest,base,{...base,draft:'New draft',research:{...base.research,channel:'LinkedIn DM'}});
assert.equal(merged.notes,'Concurrent notes');assert.equal(merged.research.linkedIn,latest.research.linkedIn);assert.equal(merged.research.sourceUrl,base.research.sourceUrl);assert.equal(merged.newField,'preserved');assert.equal(merged.draft,'New draft');
console.log('Passed: channel round trips, subject persistence, connection length, draft edits, unrelated and concurrent field preservation');
